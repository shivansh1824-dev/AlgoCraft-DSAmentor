/**
 * 2. Export Problem Sheet with Section-wise Checkboxes
 */
export function exportSheetMarkdown(sheet) {
  if (!sheet) return;

  const title = sheet.title || "DSA_Problem_Sheet";
  const safeFilename = `${title.toLowerCase().replace(/[^a-z0-9]/g, "_")}.md`;

  const total = sheet.sections?.reduce((sum, s) => sum + (s.problems?.length || 0), 0) || 0;
  const completed = sheet.sections?.reduce(
    (sum, s) => sum + (s.problems?.filter((p) => p.completed)?.length || 0),
    0
  ) || 0;
  const pct = total > 0 ? Math.round((completed / total) * 100) : 0;

  let md = `# 📋 ${title}
> ${sheet.description || "Curated DSA Problem Sheet on AlgoCraft"}
> **Progress:** ${completed}/${total} Solved (${pct}%)

---

`;

  if (sheet.sections && sheet.sections.length > 0) {
    sheet.sections.forEach((sec, idx) => {
      const secTotal = sec.problems?.length || 0;
      const secDone = sec.problems?.filter((p) => p.completed)?.length || 0;
      md += `### ${idx + 1}. ${sec.title} (${secDone}/${secTotal})\n\n`;

      if (sec.problems && sec.problems.length > 0) {
        sec.problems.forEach((prob) => {
          const check = prob.completed ? "[x]" : "[ ]";
          const link = prob.url ? `([Link](${prob.url}))` : "";
          md += `- ${check} **${prob.title}** \`[${prob.difficulty || "Medium"}]\` ${link}\n`;
        });
      } else {
        md += `*No problems added to this section yet.*\n`;
      }
      md += "\n";
    });
  }

  md += `---
*Exported from AlgoCraft Sheets Studio — Track your progress anywhere!*
`;

  downloadFile(safeFilename, md);
}

