/**
 * exportUtils.js
 * Utility functions for exporting solutions, problem sheets, and candidate portfolios
 * into clean GitHub-flavored Markdown (.md) or triggering printer-friendly views.
 */

// Helper to download a string as a file in the browser
export function downloadFile(filename, content, mimeType = "text/markdown;charset=utf-8;") {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

